/**
 * Applies the selected language to the entire page DOM
 * @param {string} langCode - Language code ('en', 'np', 'ha', 'yo', 'ig')
 */
function applyLanguage(langCode) {
  const code = (langCode || 'en').toLowerCase();
  const dict = TRANSLATIONS[code] || TRANSLATIONS['en'];

  document.documentElement.lang = code;

  // 1. Masthead Brand Slogan
  const sloganEl = document.querySelector('.brand-slogan');
  if (sloganEl) sloganEl.textContent = dict.slogan;

  // 2. Masthead Action Buttons
  const publishSpan = document.querySelector('#adminPublishBtn span');
  if (publishSpan) publishSpan.textContent = dict.publishBtn;

  const signInSpan = document.getElementById('signInNavLabel');
  if (signInSpan) signInSpan.textContent = dict.signInBtn;

  const subscribeNavBtn = document.getElementById('subscribeNavBtn');
  if (subscribeNavBtn) subscribeNavBtn.textContent = dict.subscribeBtn;

  const bookmarksBtn = document.getElementById('openBookmarksBtn');
  if (bookmarksBtn) bookmarksBtn.setAttribute('title', dict.openBookmarksBtn);

  // 3. Search Inputs
  const searchInput = document.getElementById('searchInput');
  if (searchInput) searchInput.setAttribute('placeholder', dict.searchPlaceholder);

  const drawerSearchInput = document.getElementById('drawerSearchInput');
  if (drawerSearchInput) drawerSearchInput.setAttribute('placeholder', dict.searchPlaceholder);

  // 4. Primary Navigation Links
  if (dict.nav) {
    Object.keys(dict.nav).forEach(cat => {
      const navLink = document.querySelector(`.nav-link[data-category="${cat}"]`);
      if (navLink) navLink.textContent = dict.nav[cat];
    });
  }

  // 5. Mobile Drawer Navigation Links
  if (dict.drawer) {
    Object.keys(dict.drawer).forEach(cat => {
      const drawerLinkSpan = document.querySelector(`.classy-nav-link[data-category="${cat}"] span`);
      if (drawerLinkSpan) drawerLinkSpan.textContent = dict.drawer[cat];
    });

    const drawerBookmarksSpan = document.querySelector('#drawerBookmarksBtn span');
    if (drawerBookmarksSpan) drawerBookmarksSpan.textContent = dict.drawer.savedStories;

    const drawerSubscribeBtn = document.getElementById('drawerSubscribeBtn');
    if (drawerSubscribeBtn) drawerSubscribeBtn.textContent = dict.drawer.subscribePill;

    const drawerAdminPublishSpan = document.querySelector('#drawerAdminPublishBtn span');
    if (drawerAdminPublishSpan) drawerAdminPublishSpan.textContent = dict.drawer.publishDesk;
  }

  // 6. Section Badges & Headings
  const hotPill = document.querySelector('.badge-pill.hot');
  if (hotPill) hotPill.textContent = dict.badges.hotNow;

  const trendingHeader = document.querySelector('.trending-header span');
  if (trendingHeader) trendingHeader.textContent = dict.badges.trendingHeader;

  const breakingHeader = document.querySelector('.breaking-feed-header span');
  if (breakingHeader) breakingHeader.textContent = dict.badges.breakingHeader;

  // National Spotlight heading
  const spotlightHeader = document.querySelector('.section-col-left .section-title');
  if (spotlightHeader) spotlightHeader.textContent = dict.badges.nationalSpotlight;

  // Popular Across Nigeria heading
  const popularHeader = document.querySelector('.section-col-right .section-title');
  if (popularHeader) popularHeader.textContent = dict.badges.popularHeader;

  // Editor's Pick heading
  const editorHeader = document.querySelector('.editor-choice-column .section-title');
  if (editorHeader) editorHeader.textContent = dict.badges.editorPickHeader;

  // Special Features heading
  const specialHeader = document.querySelector('.worth-reading-column .section-title');
  if (specialHeader) specialHeader.textContent = dict.badges.specialFeaturesHeader;

  // App Banner
  const appBannerH2 = document.querySelector('.app-banner-text h2');
  if (appBannerH2) appBannerH2.textContent = dict.badges.appTitle;

  const appBannerP = document.querySelector('.app-banner-text p');
  if (appBannerP) appBannerP.textContent = dict.badges.appSubtitle;

  // Footer About & Headings
  const footerSlogan = document.querySelector('.footer-brand .slogan');
  if (footerSlogan) footerSlogan.textContent = dict.badges.footerAboutSlogan;

  const footerAboutP = document.querySelector('.footer-brand p');
  if (footerAboutP) footerAboutP.textContent = dict.badges.footerAboutText;

  const footerBriefingH4 = document.querySelector('.footer-newsletter h4');
  if (footerBriefingH4) footerBriefingH4.textContent = dict.badges.briefingTitle;

  const footerBriefingP = document.querySelector('.footer-newsletter p');
  if (footerBriefingP) footerBriefingP.textContent = dict.badges.briefingSubtitle;

  const footerSubmitBtn = document.querySelector('.footer-newsletter button');
  if (footerSubmitBtn) footerSubmitBtn.textContent = dict.badges.subscribeButton;

  // 7. Dynamic Article Titles & Excerpts on the Home Page
  if (dict.articles) {
    Object.keys(dict.articles).forEach(articleId => {
      const trans = dict.articles[articleId];

      // Hero headline & excerpt
      if (articleId === 'hero-hot-now') {
        const heroTitle = document.querySelector('[data-article-id="hero-hot-now"]');
        if (heroTitle && trans.title) heroTitle.textContent = trans.title;

        const heroExcerpt = document.querySelector('.hero-excerpt');
        if (heroExcerpt && trans.excerpt) heroExcerpt.textContent = trans.excerpt;
        return;
      }

      // Trending card titles
      const card = document.querySelector(`[data-article-id="${articleId}"]`);
      if (card) {
        const titleEl = card.querySelector(
          '.trending-title, .breaking-title, .feature-card-title, .popular-title, .editor-title, .video-card-title, .worth-item-title'
        );
        if (titleEl && trans.title) titleEl.textContent = trans.title;

        const excerptEl = card.querySelector('.popular-excerpt, .editor-excerpt, .hero-excerpt');
        if (excerptEl && trans.excerpt) excerptEl.textContent = trans.excerpt;
      }
    });
  }

  // 8. Update in-memory BLOG_ARTICLES if available so modals also render in the active language
  if (typeof BLOG_ARTICLES !== 'undefined' && dict.articles) {
    BLOG_ARTICLES.forEach(art => {
      if (dict.articles[art.id]) {
        const trans = dict.articles[art.id];
        if (trans.title) art.title = trans.title;
        if (trans.excerpt) art.excerpt = trans.excerpt;
      }
    });
  }

  // 9. Update the Language Toggle Button Pill & active item
  const langToggleBtn = document.getElementById('langToggleBtn');
  if (langToggleBtn) {
    const span = langToggleBtn.querySelector('.current-lang');
    if (span) span.textContent = code.toUpperCase();
  }

  const langDropdown = document.getElementById('langDropdown');
  if (langDropdown) {
    langDropdown.querySelectorAll('.lang-item').forEach(item => {
      const itemCode = (item.getAttribute('data-lang') || '').toLowerCase();
      item.classList.toggle('selected', itemCode === code);
    });
  }

  // Persist preference
  localStorage.setItem('nu_selected_lang', code);

  // Dispatch global event for other components if needed
  if (typeof window !== 'undefined' && typeof CustomEvent === 'function') {
    window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang: code, name: dict.langName } }));
  }
}

// Make accessible on window and module environments
if (typeof window !== 'undefined') {
  window.TRANSLATIONS = TRANSLATIONS;
  window.applyLanguage = applyLanguage;
}
if (typeof module !== 'undefined' && module.exports) {
  module.exports = { TRANSLATIONS, applyLanguage };
}
